// Builds real Office/PDF files in the browser from structured content.
import { marked } from 'marked';

const safeName = (s, ext) => `${(s || 'jarvis').replace(/[\\/:*?"<>|]+/g, '').replace(/\s+/g, ' ').trim().slice(0, 80).replace(/[.\s]+$/, '') || 'jarvis'}.${ext}`;

export function download(blob, filename) {
  const a = document.createElement('a');
  a.href = URL.createObjectURL(blob);
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}

const plain = (s) => String(s || '')
  .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '$1 ($2)')
  .replace(/[*_`~]{1,3}([^*_`~]+)[*_`~]{1,3}/g, '$1')
  .replace(/^#+\s*/, '')
  .trim();

/** Convert a Markdown answer into the document spec used by the builders. */
export function markdownToDoc(md, fallbackTitle = 'Jarvis') {
  const tokens = marked.lexer(md || '');
  const doc = { title: '', sections: [] };
  let cur = null;
  const ensure = () => { if (!cur) { cur = { heading: '', paragraphs: [], bullets: [] }; doc.sections.push(cur); } return cur; };
  for (const t of tokens) {
    if (t.type === 'heading') {
      if (!doc.title && t.depth === 1) { doc.title = plain(t.text); continue; }
      cur = { heading: plain(t.text), paragraphs: [], bullets: [] };
      doc.sections.push(cur);
    } else if (t.type === 'paragraph' || t.type === 'text') {
      ensure().paragraphs.push(plain(t.text));
    } else if (t.type === 'list') {
      for (const it of t.items) ensure().bullets.push(plain(it.text));
    } else if (t.type === 'code') {
      ensure().paragraphs.push(t.text);
    } else if (t.type === 'blockquote') {
      ensure().paragraphs.push(plain(t.text));
    } else if (t.type === 'table') {
      const s = ensure();
      s.paragraphs.push(t.header.map((h) => plain(h.text)).join(' | '));
      for (const r of t.rows) s.paragraphs.push(r.map((c) => plain(c.text)).join(' | '));
    }
  }
  if (!doc.title) {
    const first = doc.sections[0]?.paragraphs?.[0] || fallbackTitle;
    doc.title = first.replace(/^Subject:\s*/i, '').slice(0, 70);
  }
  return doc;
}

export async function buildDocx(spec) {
  const d = await import('docx');
  const { Document, Packer, Paragraph, HeadingLevel, TextRun, AlignmentType } = d;
  const children = [new Paragraph({ text: spec.title || 'Document', heading: HeadingLevel.TITLE })];
  if (spec.subtitle) children.push(new Paragraph({ children: [new TextRun({ text: spec.subtitle, italics: true, color: '555555' })], spacing: { after: 240 } }));
  for (const s of spec.sections || []) {
    if (s.heading) children.push(new Paragraph({ text: s.heading, heading: HeadingLevel.HEADING_1, spacing: { before: 240, after: 120 } }));
    for (const p of s.paragraphs || []) children.push(new Paragraph({ children: [new TextRun(p)], spacing: { after: 120 }, alignment: AlignmentType.LEFT }));
    for (const b of s.bullets || []) children.push(new Paragraph({ text: b, bullet: { level: 0 } }));
  }
  const doc = new Document({
    creator: 'Jarvis',
    title: spec.title,
    styles: { default: { document: { run: { font: 'Calibri', size: 22 } } } },
    sections: [{ children }],
  });
  return { blob: await Packer.toBlob(doc), name: safeName(spec.title, 'docx') };
}

export async function buildPdf(spec) {
  const { jsPDF } = await import('jspdf');
  const pdf = new jsPDF({ unit: 'pt', format: 'a4' });
  const W = pdf.internal.pageSize.getWidth();
  const H = pdf.internal.pageSize.getHeight();
  const M = 56;
  let y = M;
  const need = (h) => { if (y + h > H - M) { pdf.addPage(); y = M; } };
  const write = (text, size, style = 'normal', color = [30, 30, 30], indent = 0, gap = 6) => {
    pdf.setFont('helvetica', style);
    pdf.setFontSize(size);
    pdf.setTextColor(...color);
    const lines = pdf.splitTextToSize(String(text), W - M * 2 - indent);
    for (const ln of lines) { need(size * 1.35); pdf.text(ln, M + indent, y); y += size * 1.35; }
    y += gap;
  };
  pdf.setFillColor(15, 140, 170);
  pdf.rect(0, 0, W, 6, 'F');
  write(spec.title || 'Document', 22, 'bold', [10, 40, 60], 0, 4);
  if (spec.subtitle) write(spec.subtitle, 12, 'italic', [90, 90, 90], 0, 10);
  for (const s of spec.sections || []) {
    if (s.heading) { y += 6; write(s.heading, 14, 'bold', [15, 110, 140], 0, 4); }
    for (const p of s.paragraphs || []) write(p, 11);
    for (const b of s.bullets || []) {
      need(16);
      pdf.setFont('helvetica', 'normal'); pdf.setFontSize(11); pdf.setTextColor(15, 140, 170);
      pdf.text('•', M + 6, y);
      write(b, 11, 'normal', [30, 30, 30], 20, 2);
    }
  }
  const pages = pdf.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    pdf.setPage(i);
    pdf.setFontSize(9); pdf.setTextColor(150, 150, 150);
    pdf.text(`Generated by Jarvis · page ${i} of ${pages}`, M, H - 28);
  }
  return { blob: pdf.output('blob'), name: safeName(spec.title, 'pdf') };
}

export async function buildPptx(spec) {
  const mod = await import('pptxgenjs');
  const PptxGenJS = mod.default || mod;
  const p = new PptxGenJS();
  p.layout = 'LAYOUT_WIDE';
  p.title = spec.title || 'Presentation';
  const BG = '061A26';
  const CY = '3FE0FF';
  const TX = 'E6F7FB';
  const t = p.addSlide();
  t.background = { color: BG };
  t.addShape(p.ShapeType.rect, { x: 0, y: 0, w: 13.33, h: 0.12, fill: { color: CY } });
  t.addText(spec.title || 'Presentation', { x: 0.8, y: 2.4, w: 11.7, h: 1.4, fontSize: 40, bold: true, color: TX, fontFace: 'Segoe UI' });
  if (spec.subtitle) t.addText(spec.subtitle, { x: 0.8, y: 3.8, w: 11.7, h: 0.8, fontSize: 20, color: CY, fontFace: 'Segoe UI' });
  (spec.slides || []).forEach((s, i) => {
    const sl = p.addSlide();
    sl.background = { color: BG };
    sl.addShape(p.ShapeType.rect, { x: 0.6, y: 0.55, w: 0.08, h: 0.7, fill: { color: CY } });
    sl.addText(s.title || `Slide ${i + 1}`, { x: 0.85, y: 0.45, w: 11.8, h: 0.9, fontSize: 30, bold: true, color: TX, fontFace: 'Segoe UI' });
    const bullets = (s.bullets || []).map((b) => ({ text: b, options: { bullet: { code: '25B8' }, color: TX, breakLine: true } }));
    if (bullets.length) sl.addText(bullets, { x: 0.85, y: 1.6, w: 11.8, h: 5.2, fontSize: 20, fontFace: 'Segoe UI', valign: 'top', paraSpaceAfter: 10 });
    sl.addText(`${i + 2}`, { x: 12.3, y: 7.0, w: 0.6, h: 0.3, fontSize: 10, color: '6F97A6', align: 'right' });
    if (s.notes) sl.addNotes(s.notes);
  });
  const blob = await p.write({ outputType: 'blob' });
  return { blob, name: safeName(spec.title, 'pptx') };
}

const toNum = (v) => {
  if (typeof v !== 'string') return v;
  const s = v.trim();
  if (/^-?\d{1,3}(,\d{3})+(\.\d+)?$/.test(s)) return Number(s.replace(/,/g, ''));
  if (/^-?\d+(\.\d+)?$/.test(s)) return Number(s);
  return v;
};

export async function buildXlsx(spec) {
  const mod = await import('exceljs/dist/exceljs.min.js');
  const ExcelJS = mod.default || mod;
  const wb = new ExcelJS.Workbook();
  wb.creator = 'Jarvis';
  const used = new Set();
  for (const sh of spec.sheets || []) {
    let name = (sh.name || 'Sheet').replace(/[\\/?*[\]:]/g, '').slice(0, 31) || 'Sheet';
    while (used.has(name)) name = `${name.slice(0, 28)}_${used.size}`;
    used.add(name);
    const ws = wb.addWorksheet(name, { views: [{ state: 'frozen', ySplit: 1 }] });
    const cols = sh.columns || [];
    ws.addRow(cols);
    for (const r of sh.rows || []) ws.addRow(cols.map((_, i) => toNum(r[i] ?? '')));
    const head = ws.getRow(1);
    head.font = { bold: true, color: { argb: 'FFFFFFFF' } };
    head.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0F6E8C' } };
    cols.forEach((c, i) => {
      let w = String(c).length;
      for (const r of sh.rows || []) w = Math.max(w, String(r[i] ?? '').length);
      ws.getColumn(i + 1).width = Math.min(60, Math.max(10, w + 2));
    });
    if (cols.length) ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: cols.length } };
  }
  if (!wb.worksheets.length) wb.addWorksheet('Sheet1');
  const buf = await wb.xlsx.writeBuffer();
  return { blob: new Blob([buf], { type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' }), name: safeName(spec.title, 'xlsx') };
}

export async function buildFile(format, spec) {
  if (format === 'docx') return buildDocx(spec);
  if (format === 'pdf') return buildPdf(spec);
  if (format === 'pptx') return buildPptx(spec);
  if (format === 'xlsx') return buildXlsx(spec);
  throw new Error(`Unknown format ${format}`);
}

/** One-line description of a created file for the chat log. */
export function describeSpec(format, spec) {
  if (format === 'pptx') return `${(spec.slides || []).length + 1} slides`;
  if (format === 'xlsx') return `${(spec.sheets || []).length} sheet(s), ${(spec.sheets || []).reduce((n, s) => n + (s.rows || []).length, 0)} rows`;
  return `${(spec.sections || []).length} sections`;
}
